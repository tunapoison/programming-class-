import math

num1 = int(input("Escreve um número: "))
num2 = int(input("Escreve outro número: "))

print(f"A soma dos dois números é {num1 + num2}.")
print(f"A subtração dos dois números é {num1 - num2}.")
print(f"A multiplicação dos dois números é {num1 * num2}.")
print(f"A divisão dos dois números é {num1 / num2: .5f}.")
print(f"A raiz quadrada do primeiro número é {math.sqrt(num1): .5f}.")
print(f"A raiz quadrada do primeiro número é {math.sqrt(num2): .5f}.")